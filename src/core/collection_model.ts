export function parseCollectionFields(raw: unknown): CollectionField[] {
  if (!Array.isArray(raw)) {
    return [];
  }

  const fields: CollectionField[] = [];
  for (const entry of raw) {
    if (!entry || typeof entry !== "object") {
      continue;
    }
    const record = entry as Record<string, unknown>;
    const name = typeof record.name === "string" ? record.name : typeof record.Name === "string" ? record.Name : "";
    if (!name) {
      continue;
    }
    fields.push({
      name,
      type: typeof record.type === "string" ? record.type : typeof record.Type === "string" ? record.Type : "",
      system: Boolean(record.system ?? record.System),
      hidden: Boolean(record.hidden ?? record.Hidden),
      raw: record,
    });
  }

  return fields;
}

export function normalizeCollectionFields(collection: Collection): void {
  if (collection.Fields.length === 0 && collection.fields.length > 0) {
    try {
      collection.Fields = FieldsList.fromJSON(JSON.stringify(collection.fields));
    } catch {
      collection.Fields = new FieldsList();
    }
  }

  if (collection.Fields.length > 0) {
    collection.fields = parseCollectionFields(collection.Fields.toJSON());
  }
}

export function collectionFromRow(row: CollectionRow): Collection {
  let fieldsRaw: unknown = [];
  let fieldsList = new FieldsList();
  if (typeof row.fields === "string") {
    try {
      fieldsRaw = JSON.parse(row.fields);
    } catch {
      fieldsRaw = [];
    }
    try {
      fieldsList = FieldsList.fromJSON(row.fields);
    } catch {
      fieldsList = new FieldsList();
    }
  }

  let indexes: unknown = [];
  if (typeof row.indexes === "string") {
    try {
      indexes = JSON.parse(row.indexes);
    } catch {
      indexes = [];
    }
  }

  const collection = new Collection({
    id: row.id,
    name: row.name,
    type: row.type,
    system: toBoolValue(row.system),
    fields: parseCollectionFields(fieldsRaw),
    Fields: fieldsList,
    indexes: Array.isArray(indexes) ? (indexes.filter((value) => typeof value === "string") as string[]) : [],
    listRule: row.listRule ?? null,
    viewRule: row.viewRule ?? null,
    createRule: row.createRule ?? null,
    updateRule: row.updateRule ?? null,
    deleteRule: row.deleteRule ?? null,
    created: row.created ? ParseDateTime(row.created) : undefined,
    updated: row.updated ? ParseDateTime(row.updated) : undefined,
  });

  if (typeof row.options === "string") {
    collection.RawOptions = JSONRaw.parse(row.options);
    collection.unmarshalRawOptions();
  }

  collection.markNew(false);
  return collection;
}

export function applyCollectionData(collection: Collection, data: Record<string, unknown>): void {
  if (typeof data.name === "string") {
    collection.name = data.name;
  }
  if (typeof data.type === "string") {
    collection.type = data.type;
  }
  if (typeof data.system === "boolean") {
    collection.system = data.system;
  } else if (typeof data.system === "number") {
    collection.system = Boolean(data.system);
  }
  if (Array.isArray(data.fields)) {
    try {
      collection.Fields = FieldsList.fromJSON(JSON.stringify(data.fields));
    } catch {
      collection.Fields = new FieldsList();
    }
  }
  if (Array.isArray(data.indexes)) {
    collection.indexes = data.indexes.filter((value) => typeof value === "string") as string[];
  }
  if (data.listRule === null || typeof data.listRule === "string") {
    collection.listRule = data.listRule as string | null;
  }
  if (data.viewRule === null || typeof data.viewRule === "string") {
    collection.viewRule = data.viewRule as string | null;
  }
  if (data.createRule === null || typeof data.createRule === "string") {
    collection.createRule = data.createRule as string | null;
  }
  if (data.updateRule === null || typeof data.updateRule === "string") {
    collection.updateRule = data.updateRule as string | null;
  }
  if (data.deleteRule === null || typeof data.deleteRule === "string") {
    collection.deleteRule = data.deleteRule as string | null;
  }
  if (typeof data.options === "object" && data.options) {
    collection.options = data.options as Record<string, unknown>;
  }
  collection.options = data;
}

