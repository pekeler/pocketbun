  initDefaultFields(): void {
    switch (this.type) {
      case CollectionTypeBase:
        this.initIdField();
        break;
      case CollectionTypeAuth:
        this.initIdField();
        this.initPasswordField();
        this.initTokenKeyField();
        this.initEmailField();
        this.initEmailVisibilityField();
        this.initVerifiedField();
        break;
      case CollectionTypeView:
        break;
      default:
        this.initIdField();
        break;
    }

    this.fields = parseCollectionFields(this.Fields.toJSON());
  }

  initIdField(): void {
    const existing = this.Fields.GetByName(FieldNameId) as TextField | null;
    if (!existing) {
      const field = new TextField();
      field.Name = FieldNameId;
      field.System = true;
      field.PrimaryKey = true;
      field.Required = true;
      field.Min = 15;
      field.Max = 15;
      field.Pattern = defaultLowercaseRecordIdPattern;
      field.AutogeneratePattern = "[a-z0-9]{15}";
      this.Fields = NewFieldsList(field, ...this.Fields);
    } else {
      existing.System = true;
      existing.Required = true;
      existing.PrimaryKey = true;
      existing.Hidden = false;
      if (!existing.Pattern) {
        existing.Pattern = defaultLowercaseRecordIdPattern;
      }
    }
  }

  initPasswordField(): void {
    const existing = this.Fields.GetByName(FieldNamePassword) as PasswordField | null;
    if (!existing) {
      const field = new PasswordField();
      field.Name = FieldNamePassword;
      field.System = true;
      field.Hidden = true;
      field.Required = true;
      field.Min = 8;
      this.Fields.Add(field);
    } else {
      existing.System = true;
      existing.Hidden = true;
      existing.Required = true;
    }
  }

  initTokenKeyField(): void {
    const existing = this.Fields.GetByName(FieldNameTokenKey) as TextField | null;
    if (!existing) {
      const field = new TextField();
      field.Name = FieldNameTokenKey;
      field.System = true;
      field.Hidden = true;
      field.Min = 30;
      field.Max = 60;
      field.Required = true;
      field.AutogeneratePattern = "[a-zA-Z0-9]{50}";
      this.Fields.Add(field);
    } else {
      existing.System = true;
      existing.Hidden = true;
      existing.Required = true;
    }

    if (!findSingleColumnUniqueIndex(this.indexes, FieldNameTokenKey)[1]) {
      this.indexes = [
        ...this.indexes,
        `CREATE UNIQUE INDEX \`${this.fieldIndexName(FieldNameTokenKey)}\` ON \`${this.name}\` (\`${FieldNameTokenKey}\`)`,
      ];
    }
  }

