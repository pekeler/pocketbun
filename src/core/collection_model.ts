function serializeOAuth2(config: OAuth2Config, safe: boolean): Record<string, unknown> {
  const providers = config.Providers ?? (safe ? [] : null);
  const mappedProviders = providers
    ? providers.map((provider) => {
        const record: Record<string, unknown> = {
          pkce: provider.PKCE,
          name: provider.Name,
          clientId: provider.ClientId,
          authURL: provider.AuthURL,
          tokenURL: provider.TokenURL,
          userInfoURL: provider.UserInfoURL,
          displayName: provider.DisplayName,
          extra: provider.Extra,
        };
        if (!safe && provider.ClientSecret) {
          record.clientSecret = provider.ClientSecret;
        }
        return record;
      })
    : null;

  return {
    providers: mappedProviders,
    mappedFields: {
      id: config.MappedFields.Id,
      name: config.MappedFields.Name,
      username: config.MappedFields.Username,
      avatarURL: config.MappedFields.AvatarURL,
    },
    enabled: config.Enabled,
  };
}

function serializeToken(config: TokenConfigValue, safe: boolean): Record<string, unknown> {
  const record: Record<string, unknown> = {
    duration: config.Duration,
  };
  if (!safe && config.Secret) {
    record.secret = config.Secret;
  }
  return record;
}

