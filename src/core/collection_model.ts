  updateGeneratedIdIfExists(app: App): void {
    if (!this.IsNew() || this.id === "" || this.id !== this.#autogeneratedId) {
      return;
    }

    let newId = this.idChecksum();

    for (let i = 2; i < 1000; i += 1) {
      const exists = app.db().query("select id from _collections where id = ? limit 1").get(newId) as
        | { id?: string }
        | undefined;
      if (!exists?.id) {
        break;
      }
      newId = this.idChecksum() + String(i);
    }

    if (this.id === newId) {
      return;
    }

    for (let i = 0; i < this.indexes.length; i += 1) {
      const parsed = parseIndex(this.indexes[i] ?? "");
      const original = parsed.indexName;
      parsed.indexName = parsed.indexName.replaceAll(this.id, newId);
      if (parsed.indexName !== original) {
        this.indexes[i] = parsed.build();
      }
    }

    this.id = newId;
  }

