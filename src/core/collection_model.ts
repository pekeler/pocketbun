  fieldIndexName(field: string): string {
    let name = `idx_${field}_`;

    if (this.id) {
      name += this.id;
    } else if (this.name) {
      name += this.name;
    } else {
      name += pseudorandomStringWithAlphabet(10, DefaultIdAlphabet);
    }

    return name.length > 64 ? name.slice(0, 64) : name;
  }

