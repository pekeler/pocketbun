  unmarshalRawOptions(): Error | null {
    let raw: unknown = null;
    try {
      raw = this.RawOptions.toJSON();
    } catch {
      raw = null;
    }

    if (!raw || typeof raw !== "object") {
      return null;
    }

    if (this.IsView()) {
      const record = raw as Record<string, unknown>;
      this.ViewQuery = toStringValue(record.viewQuery ?? record.ViewQuery);
    } else if (this.IsAuth()) {
      this.applyOptions(raw as Record<string, unknown>);
    }

    return null;
  }

  UnmarshalJSON(raw: string | Record<string, unknown>): Error | null {
    const data = typeof raw === "string" ? (JSON.parse(raw) as Record<string, unknown>) : raw;
    if (this.IsNew() && this.type === "") {
      const minimalType = toStringValue(data.type);
      const minimalName = toStringValue(data.name);
      const minimalId = toStringValue(data.id);
      const blank = NewCollection(minimalType, minimalName, minimalId);
      this.copyFrom(blank);
    }
    applyCollectionData(this, data);
    return null;
  }

